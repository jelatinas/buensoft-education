-- 5. TABLA DE CURSOS (Antes Materias)
CREATE TABLE IF NOT EXISTS public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABLA DE CLASES (Antes Lecciones)
CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descripcion TEXT,
    course_id BIGINT REFERENCES public.courses(id) ON DELETE CASCADE,
    assigned_time_minutes INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(titulo, course_id)
);

-- 7. TABLA DE TEMAS (Antes Microtemas)
CREATE TABLE IF NOT EXISTS public.topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    contenido TEXT,
    class_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    order_index INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. TABLA DE PREGUNTAS
CREATE TABLE IF NOT EXISTS public.preguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT REFERENCES public.topics(id) ON DELETE CASCADE,
    tipo TEXT NOT NULL CHECK (tipo IN ('multiple_choice', 'true_false', 'open')),
    pregunta TEXT NOT NULL,
    respuesta_correcta TEXT NOT NULL,
    explicacion TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. TABLA DE OPCIONES PARA PREGUNTAS DE OPCIÓN MÚLTIPLE
CREATE TABLE IF NOT EXISTS public.opciones_pregunta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id BIGINT REFERENCES public.preguntas(id) ON DELETE CASCADE,
    opcion TEXT NOT NULL,
    es_correcta BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. TABLA DE INTENTOS DE EXAMEN
CREATE TABLE IF NOT EXISTS public.intentos_examen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id TEXT NOT NULL, -- UUID o Username
    class_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    fecha_inicio TIMESTAMPTZ DEFAULT NOW(),
    fecha_fin TIMESTAMPTZ,
    calificacion NUMERIC,
    topics_covered INTEGER[], -- IDs of topics they actually studied
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. TABLA DE RESPUESTAS DEL ESTUDIANTE
CREATE TABLE IF NOT EXISTS public.respuestas_estudiante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intento_id BIGINT REFERENCES public.intentos_examen(id) ON DELETE CASCADE,
    pregunta_id BIGINT REFERENCES public.preguntas(id) ON DELETE CASCADE,
    respuesta TEXT NOT NULL,
    es_correcta BOOLEAN,
    score NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. TABLA DE PROGRESO DE LA CLASE DEL ESTUDIANTE (NUEVO)
CREATE TABLE IF NOT EXISTS public.student_class_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id TEXT NOT NULL,
    class_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    current_topic_id BIGINT REFERENCES public.topics(id),
    time_remaining_seconds INTEGER NOT NULL,
    is_in_penalty BOOLEAN DEFAULT FALSE,
    penalty_time_remaining_seconds INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(estudiante_id, class_id)
);

-- 13. TABLA DE CONFIGURACIONES (SETTINGS) (NUEVO)
CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);


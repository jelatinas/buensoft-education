
-- 1. TABLA DE TRANSACCIONES (Se mantiene para auditoría histórica)
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account TEXT NOT NULL, -- UUID o Username del emisor
    to_account TEXT NOT NULL,   -- UUID o Username del receptor
    amount NUMERIC NOT NULL,
    concept TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- LIMPIEZA DE FUNCIONES ANTIGUAS PARA EVITAR CONFLICTOS
DROP FUNCTION IF EXISTS public.transferir_creditos_estudiante(TEXT, TEXT, TEXT[], NUMERIC, TEXT, TEXT);
DROP FUNCTION IF EXISTS public.transferencia_manual_admin(TEXT, TEXT, NUMERIC, TEXT, BOOLEAN);
DROP FUNCTION IF EXISTS public.transferencia_estudiante(TEXT, TEXT, NUMERIC, TEXT);

-- 2. FUNCIÓN RPC: transferir_creditos_estudiante
-- Transfiere créditos de lecciones aprobadas (Banco -> Estudiante)
CREATE OR REPLACE FUNCTION transferir_creditos_estudiante(
    p_estudiante_id TEXT,
    p_admin_id TEXT,
    p_lecciones_ids TEXT[],
    p_monto_total NUMERIC,
    p_username TEXT,
    p_concept TEXT
) RETURNS VOID AS $$
BEGIN
    -- Registrar la transacción en el historial
    INSERT INTO public.transactions (from_account, to_account, amount, concept)
    VALUES (p_admin_id, p_estudiante_id, p_monto_total, p_concept);

    -- Restar del balance del Admin (Banco) en la tabla USERS
    UPDATE public.users 
    SET balance = COALESCE(balance, 0) - p_monto_total 
    WHERE id::text = p_admin_id OR username = p_admin_id;
    
    -- Sumar al balance del Estudiante en la tabla USERS
    UPDATE public.users 
    SET balance = COALESCE(balance, 0) + p_monto_total 
    WHERE id::text = p_estudiante_id OR username = p_estudiante_id;

    -- Marcar lecciones como pagadas (usando cast a texto para compatibilidad con UUIDs)
    UPDATE public.student_lessons 
    SET credits_transfered = true 
    WHERE id::text = ANY(p_lecciones_ids);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 3. FUNCIÓN RPC: transferencia_manual_admin
-- Movimientos manuales realizados por el Admin (Ingresos o Egresos)
CREATE OR REPLACE FUNCTION transferencia_manual_admin(
    p_estudiante_id TEXT,
    p_admin_id TEXT,
    p_monto NUMERIC,
    p_concept TEXT,
    p_es_ingreso BOOLEAN
) RETURNS VOID AS $$
DECLARE
    v_from_id TEXT;
    v_to_id TEXT;
BEGIN
    IF p_es_ingreso THEN
        v_from_id := p_admin_id;
        v_to_id := p_estudiante_id;
        
        UPDATE public.users SET balance = COALESCE(balance, 0) - p_monto WHERE id::text = v_from_id OR username = v_from_id;
        UPDATE public.users SET balance = COALESCE(balance, 0) + p_monto WHERE id::text = v_to_id OR username = v_to_id;
    ELSE
        v_from_id := p_estudiante_id;
        v_to_id := p_admin_id;
        
        UPDATE public.users SET balance = COALESCE(balance, 0) - p_monto WHERE id::text = v_from_id OR username = v_from_id;
        UPDATE public.users SET balance = COALESCE(balance, 0) + p_monto WHERE id::text = v_to_id OR username = v_to_id;
    END IF;

    INSERT INTO public.transactions (from_account, to_account, amount, concept)
    VALUES (v_from_id, v_to_id, p_monto, p_concept);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 4. FUNCIÓN RPC: transferencia_estudiante
-- Transferencias directas entre estudiantes o hacia el banco
CREATE OR REPLACE FUNCTION transferencia_estudiante(
    p_from_id TEXT,
    p_to_id TEXT,
    p_monto NUMERIC,
    p_concept TEXT
) RETURNS VOID AS $$
BEGIN
    -- Verificar fondos suficientes
    IF (SELECT COALESCE(balance, 0) FROM public.users WHERE id::text = p_from_id OR username = p_from_id) < p_monto THEN
        RAISE EXCEPTION 'Fondos insuficientes en tu cuenta';
    END IF;

    -- Ejecutar movimiento
    UPDATE public.users 
    SET balance = COALESCE(balance, 0) - p_monto 
    WHERE id::text = p_from_id OR username = p_from_id;

    UPDATE public.users 
    SET balance = COALESCE(balance, 0) + p_monto 
    WHERE id::text = p_to_id OR username = p_to_id;

    -- Registrar en historial
    INSERT INTO public.transactions (from_account, to_account, amount, concept)
    VALUES (p_from_id, p_to_id, p_monto, p_concept);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

